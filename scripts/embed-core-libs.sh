#!/usr/bin/env bash
# Write the C source that puts the core-libs sources into the aihc
# executable. The `embed-core-libs` flag of aihc-package-plan compiles this
# file. Run this script before each build with that flag.
#
# The script puts each file under core-libs into one archive. A name that
# starts with a dot is not a source, the same as in sourceTreeDigest. Each
# file is its relative path, a NUL byte, its size in decimal, a NUL byte,
# and its contents. The files are in byte order of their paths. lz4
# compresses the archive into one frame with its content size. The C file
# gives the frame as the array aihc_core_libs_lz4 and its size as
# aihc_core_libs_lz4_size.
set -euo pipefail

usage() {
	cat <<'USAGE'
Usage: scripts/embed-core-libs.sh [--output FILE]

  --output FILE  Write the C source to FILE (default:
                 tooling/aihc-package-plan/cbits/generated/core_libs.c)
USAGE
}

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
output="$repo_root/tooling/aihc-package-plan/cbits/generated/core_libs.c"

while [ "$#" -gt 0 ]; do
	case "$1" in
	--output)
		output="${2:?--output needs a file}"
		shift 2
		;;
	--help)
		usage
		exit 0
		;;
	*)
		usage >&2
		exit 2
		;;
	esac
done

for tool in lz4 od; do
	if ! command -v "$tool" >/dev/null; then
		echo "embed-core-libs: $tool is not on PATH. Use nix develop." >&2
		exit 1
	fi
done

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

archive() {
	cd "$repo_root/core-libs"
	find . -mindepth 1 -name '.*' -prune -o -type f -print0 |
		LC_ALL=C sort -z |
		while IFS= read -r -d '' path; do
			relative="${path#./}"
			size="$(wc -c <"$path" | tr -d ' ')"
			printf '%s\0%s\0' "$relative" "$size"
			cat "$path"
		done
}

archive >"$work/core-libs.archive"
lz4 -q -12 --content-size "$work/core-libs.archive" "$work/core-libs.lz4"
frame_size="$(wc -c <"$work/core-libs.lz4" | tr -d ' ')"

{
	echo "/* Generated by scripts/embed-core-libs.sh. Do not edit. */"
	echo "#include <stdint.h>"
	echo ""
	echo "const uint64_t aihc_core_libs_lz4_size = ${frame_size}u;"
	echo ""
	echo "const unsigned char aihc_core_libs_lz4[] = {"
	od -An -v -tx1 "$work/core-libs.lz4" |
		tr -s ' ' |
		sed -e 's/^ //' -e 's/ $//' -e '/^$/d' -e 's/\([0-9a-f][0-9a-f]\)/0x\1,/g'
	echo "};"
} >"$work/core_libs.c"

mkdir -p "$(dirname "$output")"
mv "$work/core_libs.c" "$output"
echo "embed-core-libs: wrote $output ($frame_size bytes of lz4)" >&2
